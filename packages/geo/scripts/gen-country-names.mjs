#!/usr/bin/env node
/**
 * Writes src/countryNames.generated.ts — every country's name in each non-English
 * app locale, taken from Node's full ICU.
 *
 * Why generated: the mobile app runs on Hermes, which has no Intl.DisplayNames,
 * so `countryLabel()` printed English country names to Russian users. Browsers
 * have the data; the phone does not, so it ships as a table (~10 KB per locale).
 *
 *   node scripts/gen-country-names.mjs
 *
 * Re-run after adding a locale to packages/i18n or a country to the lists.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(ROOT, p), 'utf8');

const isoCodes = [
  ...new Set(
    [read('src/countries.generated.ts'), read('src/countries.ts')].flatMap((src) =>
      [...src.matchAll(/iso2:\s*['"]([A-Z]{2})['"]/g)].map((m) => m[1]),
    ),
  ),
].sort();

const i18nIndex = read('../i18n/src/index.ts');
const locales = JSON.parse(
  i18nIndex.match(/export const LOCALES = (\[[^\]]*\])/)[1].replace(/'/g, '"'),
).filter((l) => l !== 'en');

const table = {};
for (const locale of locales) {
  const names = new Intl.DisplayNames([locale], { type: 'region' });
  table[locale] = Object.fromEntries(isoCodes.map((iso) => [iso, names.of(iso)]).filter(([iso, n]) => n && n !== iso));
}

writeFileSync(
  join(ROOT, 'src', 'countryNames.generated.ts'),
  `// GENERATED by scripts/gen-country-names.mjs from Node's ICU — do not edit by hand.

/** Country names by locale, keyed by ISO 3166-1 alpha-2. English lives on \`Country.name\`. */
export const COUNTRY_NAMES: Record<string, Record<string, string>> = ${JSON.stringify(table, null, 2)};
`,
);
console.log(`countryNames.generated.ts: ${locales.join(', ')} × ${isoCodes.length} countries`);
